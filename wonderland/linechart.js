	buildMesh(dta) {
		console.log(dta);
				for(var d=1;d<dta.columns.length;d++)
				{
					var ob = this.engine.scene.addObject(this.object);
					ob.setPositionLocal([0,0,(d-1) * this.stripwidth * 1.1]);
					
					ob.name = dta.columns[d];
					
					var sz = dta.data.length;
					
					var minvalue = null;
					var maxvalue = null;
									
					
					for(var x=0;x<sz;x++)
					{
						try
						{
							dta.data[x][d] = parseFloat(dta.data[x][d]);
						}
						catch(e) {
						}
						
						if ((minvalue == null) || (dta.data[x][d] < minvalue))
							minvalue = dta.data[x][d];
						if ((maxvalue == null) || (dta.data[x][d] > maxvalue))
							maxvalue = dta.data[x][d];
					}
					
					var range = maxvalue - minvalue;
					if (range == 0) range = 1;
					
					this.indexData = [];

					this.indexData = new Uint32Array((sz-1)*6);					
					
					var touched = 0;					
					for(var i=1;i<sz;i++)
					{		
						this.indexData[touched] = i;
						this.indexData[touched+1] = i+2;
						this.indexData[touched+2] = i+3;
						this.indexData[touched+3] = i+1;
						this.indexData[touched+4] = i+0;
						this.indexData[touched+5] = i+3;
						
						//this.indexData.subarray(i, i + 6).set([touched, touched + 2, touched + 1, touched + 2, touched + 3, touched + 1]);						
						touched += 6;
					}
					this.mesh = this.engine.meshes.create({vertexCount: sz*2,indexData: this.indexData});
					
					const positions = this.mesh.attribute(MeshAttribute.Position);
					const texCoords = this.mesh.attribute(MeshAttribute.TextureCoordinate);					
					const colors = this.mesh.attribute(MeshAttribute.Color);
					const normals = this.mesh.attribute(MeshAttribute.Normal);
					
					var base = 0;
					var index = -1;
					let y = 0;
					const xscaling = this.xscale / sz;
					const yscaling = this.yscale / range;
					
					const stripleft = -this.stripwidth/2;
					const stripright = this.stripwidth/2;
					
					for(var x=0;x<sz;x+=1)
					{
						index++;
						base = x * 2;
						y = ((dta.data[x][d] - minvalue) / range) * yscaling;
						//y=0.2
						positions.set(base,[index*xscaling,y,stripleft]);
						positions.set(base+1,[index*xscaling,y,stripright]);
						
						//console.log([index*xscaling,0,0]);
						if (texCoords != null) {
							texCoords.set(base,[x/sz,0]);
							texCoords.set(base+1,[x/sz,1]);
						}
					}
					
					const normal = new Float32Array(3);
					for (let i = 0; i < this.indexData.length; i+=3) {
						//normals.set(i,[0,1,0]);
						this.surfaceNormal(
							normal,
							positions.get(this.indexData[i + 0]),
							positions.get(this.indexData[i + 1]),
							positions.get(this.indexData[i + 2])
						);
						
						/*normal[0] = 0;
						normal[1] = 1;
						normal[2] = 0;*/
						
						for (let v = 0; v < 3; ++v) {							
							normals.set(this.indexData[i + v], normal);
						}
					}
					
					var meshCmp = ob.addComponent('mesh',{
						mesh: this.mesh,
						material: this.material
					});
					
					meshCmp.active = false;
					
					this.engine.scene.dispatchReadyEvent();
				}
	}
	
	surfaceNormal(out, p1, p2, p3) {
        vec3.sub(u, p2, p1);
        vec3.sub(v, p3, p1);
        vec3.cross(out, u, v);
        vec3.normalize(out, out);
		
		/*console.log(p1);
		console.log(p2);
		console.log(p3);
		console.log(out);
		console.log("---");*/
		out[0] = Math.abs(out[0]);
		out[1] = Math.abs(out[1]);
		out[2] = Math.abs(out[2]);
		

        return out;
    }
	
	updateData() {
		
		//this.buildMesh(this.sampledata);
		//return;
		
		console.log("Sending Query...");
		fetch(this.server + "/aql/api/table", {
		  method: "POST",
		  headers: {
			"Content-Type": "application/x-www-form-urlencoded",
		  },		  
		  body: new URLSearchParams({ format: "json", query: this.query })		  
		}).then((response) => {
			response.json().then((dta) => {
				this.buildMesh(dta);
			})			
		},(err) => {
			console.log("Failure");
		});
	}
